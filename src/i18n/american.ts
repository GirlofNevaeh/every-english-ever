const ordered = [...pairs].sort((a, b) => b[0].length - a[0].length);

function matchCase(sample: string, replacement: string) {
  if (sample === sample.toUpperCase()) return replacement.toUpperCase();
  if (sample[0] === sample[0]?.toUpperCase()) return replacement[0]?.toUpperCase() + replacement.slice(1);
  return replacement;
}

export function toAmericanEnglish(text: string) {
  let next = text;
  for (const [from, to] of ordered) {
    next = next.replace(new RegExp(`\\b${from}\\b`, "gi"), (found) => matchCase(found, to));
  }
  return next;
}
